// Create a LabIcon instance
export const createIcon = (name:string, path: string) => {
  const FILL = "#7e7e7e"
  const svgstr = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${path}" fill="${FILL}" /></svg>`
  return new LabIcon({
    name,
    svgstr,
  });
}

// Create a LabIcon instance
export const createFiglinqIcon = () => {
  return new LabIcon({
    name: 'figlinq-logo',
    svgstr: figlinqLogo,
  });
}

