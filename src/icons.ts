export const getFileTypeToIcon = () => {
  const icons: any = {};
  for (const key in FILETYPE_TO_ICON) {
    const name = FILETYPE_TO_ICON[key].name;
    const icon = FILETYPE_TO_ICON[key];
    icon.icon = createIcon(name, icon.icon);
    icons[key] = icon;
  }
  return icons;
}
